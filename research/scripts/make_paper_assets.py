def rows(path: Path) -> list[dict]:
    with open(path) as fh:
        return list(csv.DictReader(fh))


def jload(path: Path) -> dict:
    return json.loads(path.read_text())


def write_result(name: str, label: str, metrics: dict, sources: list[str], readme: str) -> dict:
    d = RES / name
    d.mkdir(parents=True, exist_ok=True)
    rrlib.write_json(d / "metrics.json", {"experiment_id": name.split("_")[0], "evidence": label, "sources": sources, **metrics})
    (d / "README.md").write_text(f"# {name} ({label})\n\n{readme}\n\nGenerated by `research/scripts/make_paper_assets.py`; do not edit.\n")
    return jload(d / "metrics.json")


def save(fig, name: str, evidence: str) -> None:
    fig.text(0.995, -0.06, evidence, ha="right", va="top", fontsize=6.5, color=MUTED)
    fig.savefig(OUT / f"{name}.pdf", bbox_inches="tight")
    fig.savefig(OUT / f"{name}.png", bbox_inches="tight", dpi=170)
    plt.close(fig)
    print(f"wrote paper/figures/{name}")


