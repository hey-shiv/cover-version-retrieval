def p1_hub_concentration() -> dict:
    a1 = RES / "A1_k_sweep_long384"
    cand = rows(a1 / "candidates.csv")
    ref = np.array([float(c["hub_reference"]) for c in cand])
    kocc = np.array([float(c["kocc10"]) for c in cand])
    pct = {c["candidate_pid"]: float(p) for c, p in zip(cand, (np.argsort(np.argsort(ref)) + 0.5) / len(ref))}
    pq = rows(a1 / "per_query.csv")
    out: dict = {"n_candidates": len(cand), "bins": [f"{10 * i}-{10 * (i + 1)}%" for i in range(10)], "systems": {}}
    for k in (30, 500):
        for s in ("hyb", "hub"):
            fp = [pct[r[f"{s}_top1_K{k}"]] for r in pq if int(r[f"{s}_first_K{k}"]) != 1 and int(r[f"cov_K{k}"]) > 0]
            fp = np.array(fp)
            hist = np.histogram(fp, bins=np.linspace(0, 1, 11))[0]
            out["systems"][f"K{k}/{s}"] = {
                "n_rank1_false_positives_in_covered_queries": int(fp.size),
                "share_by_reference_decile": (hist / max(fp.size, 1)).tolist(),
                "share_top_5pct": float(np.mean(fp >= 0.95)) if fp.size else 0.0,
                "share_top_10pct": float(np.mean(fp >= 0.90)) if fp.size else 0.0,
            }
    rk = np.argsort(np.argsort(ref)), np.argsort(np.argsort(kocc))
    out["spearman_reference_vs_stage1_kocc10"] = float(np.corrcoef(rk[0], rk[1])[0, 1])
    return write_result(
        "P1_rank1_hub_concentration", "ANALYSIS of LOCAL-FULL", out,
        ["research/results/A1_k_sweep_long384/candidates.csv", "research/results/A1_k_sweep_long384/per_query.csv"],
        "For queries whose shortlist contains a cover but whose rank-1 item is not one, where does that rank-1 item sit "
        "in the catalogue-wide distribution of the probe hub reference? Uniform would put 10% in each decile.")


def p2_dev_vs_benchmark() -> dict:
    def bench(csv_path: Path, a: str, b: str) -> dict:
        r = rows(csv_path)
        return stats.boot_delta([float(x[a]) for x in r], [float(x[b]) for x in r], [x["query_wid"] for x in r])

    def dev(file: str, key_block: str, key: str) -> dict:
        d = jload(REP / file)[key_block][key]
        return {"delta": d["delta"], "ci_low": d["ci_low"], "ci_high": d["ci_high"], "n_groups": d["n_groups"]}

    h1 = RES / "H1_alignment_ablation" / "per_query.csv"
    comps = [
        {"question": "hybrid (1,500-work encoder) minus exhaustive classical alignment, 96 frames",
         "dev": dev("hybrid_dev.json", "bootstrap", "hybrid_K30_alpha0.05 - classical_alignment"),
         "benchmark": bench(REP / "benchmark_per_query.csv", "classical_alignment_ap", "hybrid_K30_alpha0.05_ap"),
         "benchmark_source": "run 1"},
        {"question": "reranking minus Stage 1 (150-epoch encoder, 384 frames)",
         "dev": dev("hybrid_dev_long384.json", "bootstrap", "hybrid_K30_alpha0.10 - global_embedding"),
         "benchmark": bench(REP / "benchmark_per_query_long384.csv", "global_embedding_ap", "hybrid_K30_alpha0.10_ap"),
         "benchmark_source": "run 4"},
        {"question": "hub correction of exhaustive classical alignment, 96 frames",
         "dev": {k: jload(REP / "hubness_correction.json")["dev_bootstrap_corrected_minus_uncorrected"][k] for k in ("delta", "ci_low", "ci_high", "n_groups")},
         "benchmark": bench(REP / "benchmark_per_query_full96.csv", "classical_alignment_ap", "classical_alignment_hubcorr_ap"),
         "benchmark_source": "run 2"},
        {"question": "profile-cosine key rotation minus no key handling, 96 frames",
         "dev": {k: -v if k == "delta" else v for k, v in dev("classical_dev.json", "bootstrap_vs_baseline", "classical_none - classical_profile_cosine").items()},
         "benchmark": bench(h1, "none_n96_ap", "profile_cosine_n96_ap"),
         "benchmark_source": "H1 (LOCAL-FULL, K = 30 rerank only)"},
    ]
    # the dev key-rotation interval must be negated too (it was stored as none - rotation)
    d4 = jload(REP / "classical_dev.json")["bootstrap_vs_baseline"]["classical_none - classical_profile_cosine"]
    comps[3]["dev"].update({"ci_low": -d4["ci_high"], "ci_high": -d4["ci_low"]})
    for c in comps:
        c["dev_interval_includes_zero"] = bool(c["dev"]["ci_low"] <= 0 <= c["dev"]["ci_high"])
        c["benchmark_interval_excludes_zero"] = bool(c["benchmark"]["ci_low"] > 0 or c["benchmark"]["ci_high"] < 0)
        c["point_estimates_disagree_in_sign"] = bool(np.sign(c["dev"]["delta"]) != np.sign(c["benchmark"]["delta"]))
    return write_result(
        "P2_dev_vs_benchmark", "ANALYSIS of FROZEN-RUN + DEV (+ LOCAL-FULL for key rotation)", {"comparisons": comps},
        ["reports/results/hybrid_dev*.json", "reports/results/classical_dev.json", "reports/results/hubness_correction.json",
         "reports/results/benchmark_per_query*.csv", "research/results/H1_alignment_ablation/per_query.csv"],
        "Each row: the same paired comparison on the 20-query development protocol (1 relevant item, 119 candidates) and on the "
        "13,000-query benchmark (12 relevant, 14,999 candidates). Deltas are AP, work-level paired bootstrap.")


