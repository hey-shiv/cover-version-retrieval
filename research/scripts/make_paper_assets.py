def fig_hub(p1: dict) -> None:
    fig, axes = plt.subplots(1, 2, figsize=(7.4, 2.8), sharey=True)
    x = np.arange(10)
    for ax, k in zip(axes, (30, 500)):
        for off, s, c, lab in ((-0.2, "hyb", SLOT[3], "uncorrected"), (0.2, "hub", SLOT[1], "hub-corrected")):
            e = p1["systems"][f"K{k}/{s}"]
            ax.bar(x + off, 100 * np.array(e["share_by_reference_decile"]), width=0.38, color=c,
                   label=f"{lab} (n = {e['n_rank1_false_positives_in_covered_queries']:,})")
        ax.axhline(10, color=MUTED, lw=1, ls=":")
        ax.set_xticks(x, [f"{10 * i + 10}" for i in x], fontsize=7)
        ax.set_title(f"K = {k}")
        ax.legend(fontsize=6.8, loc="upper left")
        ax.grid(axis="x", visible=False)
    axes[0].set_ylabel("% of rank-1 false positives")
    fig.supxlabel("candidate's hub-reference percentile (decile upper bound)", fontsize=8.5, y=-0.04)
    save(fig, "hub_concentration", "ANALYSIS of LOCAL-FULL · P1 · queries whose shortlist holds a cover but whose rank-1 item is not one · dotted: uniform")


def fig_resolution() -> None:
    dev96, dev384 = jload(REP / "hybrid_dev.json"), jload(REP / "hybrid_dev_n384.json")
    mp = lambda d, s: next(m["MAP"] for m in d["metrics"] if m["system"] == s)  # noqa: E731
    x5 = jload(RES / "X5_paired_ablations_benchmark/metrics.json")
    h1 = jload(RES / "H1_alignment_ablation/metrics.json")["variants"]
    fig, axes = plt.subplots(1, 3, figsize=(8.6, 2.7), gridspec_kw={"width_ratios": [1, 1, 1.2]})
    ax = axes[0]
    for i, (s96, s384, lab, c) in enumerate((("classical_alignment", "classical_alignment", "classical", MUTED),
                                               ("hybrid_K30_alpha0.05", "hybrid_K30_alpha0.00", "hybrid", SLOT[1]))):
        a, b = mp(dev96, s96), mp(dev384, s384)
        ax.plot([0, 1], [a, b], "-o", color=c)
        ax.text(1.06, b, f"{lab} {a:.3f}→{b:.3f}", fontsize=7, va="center", color=c)
    ax.set_xticks([0, 1], ["96", "384"]), ax.set_xlim(-0.2, 2.8), ax.set_title("Development")
    ax.set_ylabel("MAP"), ax.set_xlabel("frames")
    ax = axes[1]
    comps = x5["comparisons"]
    keys = [k for k in comps if k.startswith("resolution")]
    for i, key in enumerate(keys):
        d = comps[key]["delta_AP"] if "delta_AP" in comps[key] else comps[key]
        ax.plot([i, i], [d["ci_low"], d["ci_high"]], color=SLOT[1], lw=2)
        ax.plot([i], [d["delta"]], "o", color=SLOT[1])
    ax.axhline(0, color=MUTED, lw=1)
    ax.set_xticks(range(len(keys)), ["no hub corr.", "hub-corrected"], fontsize=7), ax.set_xlim(-0.6, len(keys) - 0.4)
    ax.set_title("Benchmark: run 3 − run 2"), ax.set_ylabel("Δ AP, 384 − 96 frames")
    ax = axes[2]
