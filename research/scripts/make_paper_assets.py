def copy_figures() -> None:
    for name, src in COPIED.items():
        if src.exists():
            shutil.copyfile(src, OUT / f"{name}{src.suffix}")
            print(f"copied paper/figures/{name}{src.suffix}")
        else:
            print(f"MISSING {src}")


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    p1, p2 = p1_hub_concentration(), p2_dev_vs_benchmark()
    fig_architecture(), fig_runs(), fig_frontier(), fig_hub(p1), fig_resolution(), fig_dev_vs_bench(p2)
    copy_figures()
    return 0


