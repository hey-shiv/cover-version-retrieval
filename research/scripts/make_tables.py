def _rep(name: str) -> dict:
    return json.loads((REP / name).read_text())


def _sysmap(run: dict) -> dict:
    return {m["system"]: m for m in run["metrics"]}


def t_config() -> None:
    import yaml

    base = yaml.safe_load((REPO / "configs" / "base.yaml").read_text())
    enc, tr, al = base["encoder"], base["training"], base["alignment"]
    summ = json.loads((REP / "training_summary_encoder_full_long.json").read_text())
    runs = [("Run 1", "benchmark.json"), ("Run 2", "benchmark_full96.json"), ("Run 3", "benchmark_full384.json"), ("Run 4", "benchmark_long384.json")]
    rows = [["input", "Da-TACOS HPCP, 12 pitch classes; encoder view area-pooled to " + str(enc["input_frames"]) + " frames"],
            ["encoder", f"TCN, {enc['n_blocks']} residual blocks, kernel {enc['kernel_size']}, dilations 1-{2 ** (enc['n_blocks'] - 1)}, "
                        f"{enc['channels']} channels, receptive field {summ['receptive_field_frames']} frames"],
            ["pooling and head", f"mean and max over time, MLP to {enc['embedding_dim']}-d, L2-normalised; {summ['n_parameters']:,} parameters"],
            ["training", f"supervised contrastive (temperature {tr['temperature']}), {tr['batch_wids']} works x 2 recordings per batch, AdamW lr {tr['lr']}, "
                         f"cosine schedule, crop {tr['crop_min_fraction']}-1.0, random pitch rotation, seed {base['seed']}"],
            ["Stage 1", "exact cosine search over all candidates, self excluded, top K = " + str(base["retrieval"]["shortlist_k"])],
            ["key handling", "one of 12 rotations, chosen by cosine of time-averaged chroma profiles"],
            ["alignment", f"cosine cost, subsequence DTW, steps {al['step_sizes']}, weights {al['step_weights']}, cost / path weight"],
            ["fusion", "alpha z(global) + (1 - alpha) z(alignment) within the shortlist"],
            ["hub correction", "alignment score minus lambda x mean score against 200 training-split probe queries"]]
    for lab, f in runs:
        lk = _rep(f)["locked_from_calibration"]
        hub = lk.get("hub_correction", {}).get("lambda", "-")
        rows.append([f"{lab} locked", f"checkpoint {Path(lk['checkpoint']).parent.name}, alignment frames {lk.get('n_frames', 96)}, alpha {lk['alpha']}, lambda {hub}"])
    write("t14_config", "System configuration, read from configs/base.yaml and the locked block of each benchmark result file",
          ["component", "setting"], rows, "configs/base.yaml, reports/results/benchmark*.json, training_summary_encoder_full_long.json", colspec=r"lp{0.74\linewidth}")


def t_runtime() -> None:
    runs = [("Run 1 (96 fr.)", "benchmark.json"), ("Run 2 (96 fr.)", "benchmark_full96.json"), ("Run 3 (384 fr.)", "benchmark_full384.json"), ("Run 4 (384 fr.)", "benchmark_long384.json")]
    rows = []
    pairs = 0
    for lab, f in runs:
        r = _rep(f)
        rt, pr = r["runtime"], r["protocol"]
        pairs = pr["queries"] * (pr["candidates"] - 1)
        k = r["locked_from_calibration"]["shortlist_k"]
        exh = f"{rt['alignment_only_s']:,.0f} s ({rt['alignment_only_s'] / 3600:.2f} h)" if "alignment_only_s" in rt else "not run (about 42 h, estimated)"
        rows.append([lab, f"{rt['embedding_s']:.0f} s", f"{rt['global_search_s']:.2f} s", f"{rt['rerank_s']:.0f} s ({rt['rerank_ms_per_query']:.1f} ms/query)",
                     f"{pr['queries'] * k:,} ({100 * k / (pr['candidates'] - 1):.2f}%)", exh, f"{rt['hub_reference_s']:.0f} s" if "hub_reference_s" in rt else "-"])
    write("t15_runtime", f"Measured runtime on the benchmark ({pairs:,} query-candidate pairs); exhaustive alignment is alignment-only time; run 2 reused the run-1 alignment matrix",
          ["run", "embed 15,000 tracks", "exact search", "K = 30 rerank", "pairs aligned at K = 30", "exhaustive alignment", "hub probe reference"],
          rows, "reports/results/benchmark*.json runtime blocks")


