MISSING: list[str] = []


def load(exp: str) -> dict | None:
    p = RES / exp / "metrics.json"
    if not p.exists():
        MISSING.append(exp)
        return None
    return json.loads(p.read_text())


def ci(e: dict, d: int = 3, pct: bool = False) -> str:
    f = (lambda v: f"{100 * v:.1f}") if pct else (lambda v: f"{v:.{d}f}")
    return f"{f(e['estimate'])} [{f(e['ci_low'])}, {f(e['ci_high'])}]"


def dci(e: dict, d: int = 4) -> str:
    return f"{e['delta']:+.{d}f} [{e['ci_low']:+.{d}f}, {e['ci_high']:+.{d}f}]"


def write(name: str, caption: str, head: list[str], rows: list[list[str]], source: str, colspec: str | None = None) -> None:
    md = [f"**{caption}**", "", "| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    md += ["| " + " | ".join(r) + " |" for r in rows]
    md += ["", f"<sub>Generated by research/scripts/make_tables.py from {source}.</sub>", ""]
    (MD / f"{name}.md").write_text("\n".join(md))

    def esc(s: str) -> str:
        return s.replace("%", r"\%").replace("&", r"\&").replace("_", r"\_").replace("#", r"\#").replace("≥", r"$\geq$").replace("×", r"$\times$").replace("λ", r"$\lambda$").replace("α", r"$\alpha$").replace("→", r"$\rightarrow$").replace("|", r"$|$").replace("Δ", r"$\Delta$").replace("·", r"$\cdot$").replace("−", "$-$").replace("≤", r"$\leq$")

    wide = colspec is None and (len(head) >= 5 or any(len(" ".join(r)) > 90 for r in rows))  # scale wide tables to the text width
    tex = [f"% generated by research/scripts/make_tables.py from {source}; do not edit",
           r"\begin{table}[tbp]\centering\small", rf"\caption{{{esc(caption)}}}\label{{tab:{name}}}",
           (r"\resizebox{\linewidth}{!}{" if wide else "") + r"\begin{tabular}{" + (colspec or "l" * len(head)) + "}", r"\toprule", " & ".join(esc(h) for h in head) + r" \\", r"\midrule"]
    tex += [" & ".join(esc(c) for c in r) + r" \\" for r in rows]
    tex += [r"\bottomrule", r"\end{tabular}" + ("}" if wide else ""), r"\end{table}", ""]
    (TEX / f"{name}.tex").write_text("\n".join(tex))
    print(f"wrote {name}")


